  function icon(name, extraClass) {
    const svg = ICONS[name] || ICONS.file;
    if (extraClass) {
      return svg.replace('<svg ', '<svg class="' + extraClass + '" ');
    }
    return svg;
  }

  function toast(message, type) {
    const host = document.getElementById("toastHost");
    const el = document.createElement("div");
    el.className = "toast " + (type || "");
    el.innerHTML = message;
    host.appendChild(el);
    setTimeout(() => {
      el.style.opacity = "0";
      el.style.transition = "opacity .25s";
      setTimeout(() => el.remove(), 260);
    }, 3200);
  }

  function confirm(title, body) {
    return new Promise((resolve) => {
      const host = document.getElementById("modalHost");
      host.innerHTML =
        '<div class="modal-mask"><div class="modal-box">' +
        '<div class="modal-title">' + esc(title) + "</div>" +
        '<div class="modal-body">' + esc(body) + "</div>" +
        '<div class="modal-foot">' +
        '<button class="btn" data-act="cancel">取消</button>' +
        '<button class="btn btn-primary" data-act="ok">确认</button>' +
        "</div></div></div>";
      host.querySelector(".modal-mask").addEventListener("click", (e) => {
        if (e.target.classList.contains("modal-mask")) { host.innerHTML = ""; resolve(false); }
      });
      host.querySelectorAll("button").forEach((btn) => {
        btn.addEventListener("click", () => {
          const ok = btn.dataset.act === "ok";
          host.innerHTML = "";
          resolve(ok);
        });
      });
    });
  }

  function drawer(title, bodyHtml) {
    const host = document.getElementById("modalHost");
    host.innerHTML =
      '<div class="modal-mask" id="drawerMask"><div class="drawer-box">' +
      '<div class="drawer-head"><div class="drawer-title">' + esc(title) + '</div>' +
      '<button class="btn btn-sm btn-ghost" id="closeDrawer">✕</button></div>' +
      '<div class="drawer-body">' + bodyHtml + '</div></div></div>';
    
    const close = () => { host.innerHTML = ""; };
    host.querySelector("#closeDrawer").addEventListener("click", close);
    host.querySelector("#drawerMask").addEventListener("click", (e) => {
      if (e.target.id === "drawerMask") close();
    });
  }

  return { toast, confirm, drawer, esc, icon };
